-- 01_schema.sql  —  CONSOLIDATED FermOps / STAMM database SCHEMA (DDL only)
--
-- Complete schema for the STAMM shared Postgres (postgres:16 + timescaledb),
-- consolidating the previous init chain (01_volcado + 02_fermops_compat +
-- 03_real lead-FK lift + Carlos's rich model columns + FL updated_at trigger).
-- All DATA lives in 02_seed.sql. Idempotent where the sources were.
--
-- Project lead = projects.lead_user_id uuid REFERENCES users(id) (Camilo's
-- 2026-05-22 spec). The legacy free-text `lead` column is dropped.
--
--
-- 01_volcado.sql (sanitized for postgres:16 + timescaledb)
--
-- Generated by infra/scripts/sanitize_volcado.py from Carlos's raw pg_dump.
-- DO NOT EDIT BY HAND — re-run the sanitizer instead. Manual edits will be
-- overwritten the next time the volcado is refreshed.
--
-- Sanitizer responsibilities:
--   * Strip pg18 \restrict / \unrestrict client directives.
--   * Strip pg17+ GUCs not supported by pg16 (currently: transaction_timeout).
--   * Rewrite 'OWNER TO postgres' -> 'OWNER TO CURRENT_USER' so the dump
--     loads against our 'stamm' superuser (compose default).
--   * Prepend CREATE EXTENSION timescaledb + timescaledb_pre_restore() so
--     the dump body's _timescaledb_catalog COPY blocks land cleanly.
--   * Append timescaledb_post_restore() wrapped in DO/EXCEPTION so a
--     catalog-version mismatch doesn't abort the init script. Without this,
--     02_fermops_compat.sql would never run.
--
-- 1. schema: 
ALTER SCHEMA public OWNER TO CURRENT_USER;
COMMENT ON SCHEMA public IS '';

-- 2. extensions: timescaledb, uuid-ossp, pgcrypto
CREATE EXTENSION IF NOT EXISTS timescaledb;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;

COMMENT ON EXTENSION timescaledb IS 'Enables scalable inserts and complex queries for time-series data (Community Edition)';

COMMENT ON EXTENSION "uuid-ossp" IS 'generate universally unique identifiers (UUIDs)';

