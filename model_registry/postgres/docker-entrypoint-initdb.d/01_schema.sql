-- 8.3 Models (replaces path-only soft_sensors) ---------------------------
CREATE TABLE IF NOT EXISTS public.models (
    id                       uuid PRIMARY KEY DEFAULT public.uuid_generate_v4(),
    slug                     text NOT NULL UNIQUE,
    name                     text NOT NULL,
    description              text,
    algorithm                text NOT NULL,
    status                   text NOT NULL DEFAULT 'draft',
    version                  text NOT NULL DEFAULT '1.0.0',

    -- Algo-specific config + IO contract + metrics (all JSONB).
    config                   jsonb NOT NULL DEFAULT '{}'::jsonb,
    inputs                   jsonb NOT NULL DEFAULT '[]'::jsonb,
    outputs                  jsonb NOT NULL DEFAULT '[]'::jsonb,
    prediction_horizon_min   numeric,
    metrics                  jsonb NOT NULL DEFAULT '{}'::jsonb,

    -- Artifact (binary on disk, hash + path in DB).
    artifact_path            text,
    artifact_format          text,
    artifact_size_bytes      bigint,
    artifact_sha256          text,

    -- Training context.
    training_dataset_hash    text,
    training_started_at      timestamptz,
    training_completed_at    timestamptz,
    trained_by_user_id       uuid REFERENCES public.users(id),

    -- Single-parent lineage.
    parent_model_id          uuid REFERENCES public.models(id),
    superseded_by_model_id   uuid REFERENCES public.models(id),

    -- Federated-learning lineage.
    federation_id            uuid REFERENCES public.federations(id),
    federation_round         integer,
    federation_role          text,

    -- Validation gate.
    validation_status        text NOT NULL DEFAULT 'pending',
    validated_by_user_id     uuid REFERENCES public.users(id),
    validated_at             timestamptz,
    validation_notes         text,

    -- Deployment metadata.
    deployed_at              timestamptz,
    deployment_notes         text,

    -- Drift link.
    drift_detector_id        uuid REFERENCES public.drift_detectors(id),
    last_drift_check_at      timestamptz,
    drift_state              text,

    -- Documentation + lifecycle.
    notes                    text,
    tags                     text[] NOT NULL DEFAULT '{}',
    is_active                boolean NOT NULL DEFAULT true,
    created_at               timestamptz NOT NULL DEFAULT now(),
    updated_at               timestamptz NOT NULL DEFAULT now(),
    created_by_user_id       uuid REFERENCES public.users(id),

    CONSTRAINT models_algorithm_check CHECK (algorithm IN (
        'decision_tree', 'random_forest', 'gradient_boosting', 'ensemble',
        'svm', 'linear_regression', 'logistic_regression',
        'neural_network', 'rnn', 'cnn', 'transformer',
        'gaussian_process', 'pls', 'pca', 'kmeans',
        'custom'
    )),
    CONSTRAINT models_status_check CHECK (status IN (
        'draft', 'training', 'trained', 'deployed', 'archived'
    )),
    CONSTRAINT models_validation_check CHECK (validation_status IN (
        'pending', 'approved', 'rejected'
    )),
    CONSTRAINT models_federation_role_check CHECK (
        federation_role IS NULL OR federation_role IN (
            'local_update', 'aggregated_global'
        )
    )
);

